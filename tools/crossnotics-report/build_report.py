_PLACEHOLDER_RE = re.compile(r"\{\{([^{}]+)\}\}")


def build_term_gloss_map(computed):
    """2026-08-29 신설 — 십신ㆍ신살ㆍ구조 용어의 뜻풀이를 모델이 직접 쓰지 않고, 이 사전으로
    코드가 항상 정확하게 채워 넣는다(expand_term_placeholders 참고). 구조 용어는
    STRUCTURAL_TERM_GLOSSARY(고정, 리포트마다 동일)를 쓰고, 십신ㆍ신살은 이 리포트의
    computed.json에 이미 계산돼 있는 실제 뜻풀이를 그대로 가져온다 — 지어내지 않는다는
    1번 규칙을 코드 레벨에서도 보장한다."""
    gloss_map = dict(STRUCTURAL_TERM_GLOSSARY)
    saju = computed.get("saju") if isinstance(computed, dict) else None
    if isinstance(saju, dict):
        correspondence = saju.get("correspondence") or {}
        for item in correspondence.get("shi_shen_meanings") or []:
            if isinstance(item, dict) and item.get("name") and item.get("meaning"):
                gloss_map[item["name"]] = item["meaning"]
                # "칠살(편관)"처럼 결합 라벨이면 "칠살"만 따로 써도 인식되게 등록
                base = item["name"].split("(")[0]
                gloss_map.setdefault(base, item["meaning"])
        shensha = saju.get("shensha") or {}
        for key, label in SHENSHA_KEY_TO_LABEL.items():
            entry = shensha.get(key)
            if isinstance(entry, dict) and entry.get("meaning"):
                gloss_map[label] = entry["meaning"]
    return gloss_map


def expand_term_placeholders(obj, gloss_map, unmapped):
    """report(dict) 전체를 재귀적으로 훑어 `{{용어명}}` 표시를 실제 "용어명(뜻풀이)"로
    바꾼다. sanitize_report()와 같은 방식(구조를 가리지 않고 모든 문자열을 훑음)이라
    스키마에 필드가 추가돼도 빠뜨릴 위험이 없다.

    2026-08-29 신설 — 이전엔 "뜻풀이를 빠뜨리지 마라"는 규칙을 지키는 걸 모델에게
    맡겼는데, 실제로 화개살을 뜻풀이 없이 쓰거나(누락) 지장간 개념을 반대로 지어내는
    (오류) 사고가 났다. 생성 후에 그 실수를 찾아 경고하는 방식으로는 "터진 걸 알려줄
    뿐 애초에 안 터지게" 못 한다 — 그래서 모델의 역할을 "어디에 용어를 넣을지
    결정하는 것"까지로 좁히고, 뜻풀이 자체는 항상 이 코드가 정확한 사전에서 가져와
    채운다. 이제 모델이 뜻풀이를 빠뜨리거나 틀리게 지어낼 방법이 아예 없다 — 사전에
    없는 용어명을 썼을 때만(목록 밖 이름ㆍ오타) 예외적으로 걸리며, 그 경우 중괄호만
    벗겨서 최소한 안 깨지게 하고 unmapped에 남겨 경고로 띄운다."""
    if isinstance(obj, str):
        def _sub(m):
            term = m.group(1).strip()
            gloss = gloss_map.get(term)
            if gloss is None:
                unmapped.append(term)
                return term
            return f"{term}({gloss})"
        return _PLACEHOLDER_RE.sub(_sub, obj)
    if isinstance(obj, list):
        return [expand_term_placeholders(v, gloss_map, unmapped) for v in obj]
    if isinstance(obj, dict):
        return {k: expand_term_placeholders(v, gloss_map, unmapped) for k, v in obj.items()}
    return obj

