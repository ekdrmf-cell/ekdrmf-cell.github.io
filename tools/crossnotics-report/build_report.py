def collect_known_terms(computed):
    """computed.json 안에 실제로 존재하는 용어(간지ㆍ별자리ㆍ카드명 등)를 전부 모은다."""
    terms = set()

    def walk(obj):
        if isinstance(obj, dict):
            for v in obj.values():
                walk(v)
        elif isinstance(obj, list):
            for v in obj:
                walk(v)
        elif isinstance(obj, str) and 1 < len(obj) <= 20:
            terms.add(obj)

    walk(computed)
    return terms


def collect_valid_years(computed):
    """se_un/dae_yun/생년 등 computed.json에 실제로 등장하는 '정당한' 연도만 모은다.
    이 목록 밖의 연도가 리포트에 나오면 se_un 없이 AI가 일반 지식으로 채운 것일 가능성이
    높다(실사용 테스트에서 실제로 발견된 문제 — build_report.py 8번 규칙 참고)."""
    years = set()
    saju = computed.get("saju") or {}
    if saju.get("birth_solar"):
        years.add(int(saju["birth_solar"][:4]))
    for entry in saju.get("se_un") or []:
        years.add(entry["year"])
    for entry in saju.get("dae_yun") or []:
        years.add(entry["start_year"])
        years.add(entry["end_year"])
    return years


_PDF_FONT_CMAP = None


def _pdf_font_cmap():
    """PDF에 실제로 쓰이는 Pretendard-Regular.ttf의 글리프 테이블(cmap)을 읽어, 이 폰트가
    그릴 수 있는 유니코드 코드포인트 집합을 반환한다(최초 호출 때만 파일을 읽고 캐시함).
    Pretendard 6종 굵기는 전부 같은 글자 집합을 공유하므로 Regular 하나만 확인하면 된다."""
    global _PDF_FONT_CMAP
    if _PDF_FONT_CMAP is None:
        font_path = HERE / "fonts" / "Pretendard-Regular.ttf"
        _PDF_FONT_CMAP = set(TTFont(str(font_path)).getBestCmap().keys())
    return _PDF_FONT_CMAP


def _is_glyph_supported(ch):
    # 공백ㆍ줄바꿈 등 제어문자는 애초에 그려지는 글자가 아니므로 항상 통과.
    if ch.isspace() or ord(ch) < 0x20:
        return True
    return ord(ch) in _pdf_font_cmap()


_PAREN_LEADING_SEP_RE = re.compile(r"\(\s*[,ㆍ·]+\s*")
_PAREN_TRAILING_SEP_RE = re.compile(r"[\s,ㆍ·]+\)")
_PAREN_EMPTY_RE = re.compile(r"\(\s*[,ㆍ·]*\s*\)")


def _strip_unsupported_glyphs(text):
    """2026-08-24 추가 — 사용자 지시: "경고만 하지 말고, 폰트가 완벽하게 그릴 수 있는
    글자만 쓰도록 만들어라. 한자는 빼버려라." check_hallucination()의 경고는 사람이 보고
    다시 생성 버튼을 눌러야만 고쳐지는데, 그러면 같은 문제가 계속 재발할 여지가 남는다.
    대신 여기서 폰트가 못 그리는 글자를 실제로 제거해서, 그 문제 자체가 최종 산출물에
    나갈 수 없게 만든다. 한자만 쏙 빠지면 "화개살(壬辰)" → "화개살()"처럼 빈 괄호나
    "임진(壬辰, 물의 기운)" → "임진(, 물의 기운)"처럼 군더더기 구두점이 남을 수 있어
    그것도 같이 정리한다."""
    if not text:
        return text
    cleaned = "".join(ch for ch in text if _is_glyph_supported(ch))
    cleaned = _PAREN_LEADING_SEP_RE.sub("(", cleaned)
    cleaned = _PAREN_TRAILING_SEP_RE.sub(")", cleaned)
    cleaned = _PAREN_EMPTY_RE.sub("", cleaned)
    cleaned = re.sub(r" {2,}", " ", cleaned)
    return cleaned


def sanitize_report(obj):
    """report(dict) 전체를 재귀적으로 훑어 모든 문자열 값에서 PDF 폰트가 못 그리는 글자를
    제거한다. intro/body/heading처럼 필드를 하나하나 골라 처리하면 스키마에 필드가 추가될
    때마다 또 빠뜨릴 위험이 있으므로(실제로 이번에 그렇게 놓쳤었음), 구조를 가리지 않고
    모든 문자열을 훑는 일반적인 방식을 쓴다."""
    if isinstance(obj, str):
        return _strip_unsupported_glyphs(obj)
    if isinstance(obj, list):
        return [sanitize_report(v) for v in obj]
    if isinstance(obj, dict):
        return {k: sanitize_report(v) for k, v in obj.items()}
    return obj


_SCHEMA_TYPE_CHECK = {
    "object": lambda v: isinstance(v, dict),
    "array": lambda v: isinstance(v, list),
    "string": lambda v: isinstance(v, str),
    "null": lambda v: v is None,
    "number": lambda v: isinstance(v, (int, float)) and not isinstance(v, bool),
    "integer": lambda v: isinstance(v, int) and not isinstance(v, bool),
    "boolean": lambda v: isinstance(v, bool),
}
_SCHEMA_SAFE_DEFAULT = {"object": {}, "array": [], "string": "", "null": None}


def normalize_to_schema(value, schema, path, corrections):
    """2026-08-24 추가 — 실제로 두 번 연속 겪은 사고(action_plan이 dict 대신 문자열로,
    question_answers 항목이 dict 대신 문자열로 옴)를 계기로 만든 근본 수정. Anthropic
    구조화 출력이 스키마를 강제한다고 알려져 있지만 실전에서 타입이 어긋나는 사례가
    실제로 나왔고, 그때마다 이걸 나중에 건드리는 함수(check_hallucination만이 아니라
    report_kit.py의 PDF 렌더링까지)를 하나하나 방어 코드로 땜질하면 다음에 또 다른
    필드에서 같은 사고가 난다 — 그래서 "LLM 응답을 받는 그 즉시, 딱 한 곳에서" 스키마와
    실제 타입을 대조해 안전한 기본값으로 되돌리는 이 함수를 만들었다. 이후로는
    check_hallucination이든 report_kit.py든 전부 이미 정규화된 안전한 데이터만 보게 된다.
    무엇을 고쳤는지는 전부 corrections 리스트에 남겨 화면에 경고로 띄운다(내용이 조용히
    사라지면 안 되므로) — 코드가 안 죽는 것과, 손님에게 나갈 리포트에 구멍이 난 걸 사람이
    아는 것은 별개다."""
    types = schema.get("type")
    if types is None:
        return value
    if isinstance(types, str):
        types = [types]

    if not any(_SCHEMA_TYPE_CHECK.get(t, lambda v: False)(value) for t in types):
        # 2026-08-24 추가 — 실제 사고 원인 확인: object/array가 와야 할 자리에 문자열이
        # 왔는데, 그 문자열 내용을 열어보니 원래 의도된 JSON이 그대로 들어있었다(모델이
        # 이 필드 전체를 이중으로 문자열 인코딩한 경우). 이럴 땐 버리지 않고 다시 파싱을
        # 시도한다 — 파싱이 깨끗이 성공할 때만 쓰고, 실패하면(예: 문장 안 인용부호를
        # 이스케이프 안 해서 JSON이 실제로 깨진 경우) 안전한 기본값으로만 대체한다 —
        # 애매하게 복구를 "추측"해서 잘못된 내용을 조용히 끼워넣느니, 차라리 그 부분만
        # 비워두는 쪽이 안전하다(이 프로젝트의 "지어내지 않는다" 원칙과 같은 이유).
        if isinstance(value, str) and ("object" in types or "array" in types):
            try:
                reparsed = json.loads(value)
                if any(_SCHEMA_TYPE_CHECK.get(t, lambda v: False)(reparsed) for t in types):
                    corrections.append(f"{path}: 문자열로 이중 인코딩되어 있던 걸 재파싱으로 복구함")
                    value = reparsed
                    types = [t for t in types if _SCHEMA_TYPE_CHECK[t](value)]
            except (json.JSONDecodeError, TypeError):
                pass
        if not any(_SCHEMA_TYPE_CHECK.get(t, lambda v: False)(value) for t in types):
            default = next((_SCHEMA_SAFE_DEFAULT[t] for t in types if t in _SCHEMA_SAFE_DEFAULT), None)
            corrections.append(f"{path}: 예상 타입({'/'.join(types)})이 아님(실제: {type(value).__name__}) → {default!r}로 대체")
            return default

    if isinstance(value, dict) and "properties" in schema:
        result = dict(value)
        for key, sub_schema in schema["properties"].items():
            if key in result:
                result[key] = normalize_to_schema(result[key], sub_schema, f"{path}.{key}", corrections)
        return result

    if isinstance(value, list) and "items" in schema:
        return [normalize_to_schema(item, schema["items"], f"{path}[{i}]", corrections) for i, item in enumerate(value)]

    return value


